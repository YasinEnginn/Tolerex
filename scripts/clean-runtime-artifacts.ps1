<#
.SYNOPSIS
    Removes runtime data and logs generated by the application.

.DESCRIPTION
    Deletes data created during execution (e.g., by 'launcher' or manual runs):
    - Application logs (logs/)
    - Persistent storage data (internal/data/)
    - Measured metrics/CSV output (measured/)
    
    This effectively resets the local environment to a clean state.

.PARAMETER DryRun
    If set, prints what would be deleted without actually deleting anything.
#>
param(
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

function Remove-PathSafe {
    param(
        [Parameter(Mandatory = $true)]
        [string]$TargetPath
    )

    if (-not (Test-Path -LiteralPath $TargetPath)) {
        return
    }

    if ($DryRun) {
        Write-Host "[DRY-RUN] remove $TargetPath"
        return
    }

    try {
        $item = Get-Item -LiteralPath $TargetPath -Force
        if ($item.PSIsContainer) {
            [System.IO.Directory]::Delete($item.FullName, $true)
        } else {
            [System.IO.File]::Delete($item.FullName)
        }
        Write-Host "removed: $TargetPath"
    }
    catch {
        Write-Warning "failed to remove $TargetPath : $($_.Exception.Message)"
    }
}

# 1) Application logs
Remove-PathSafe -TargetPath "logs"

# 2) Leader runtime state file
Remove-PathSafe -TargetPath "internal/data/leader_state.json"

# 3) Member runtime data directories (member-5556, member-5557, ...)
if (Test-Path -LiteralPath "internal/data") {
    Get-ChildItem -Path "internal/data" -Directory -Filter "member-*" -ErrorAction SilentlyContinue |
        ForEach-Object { Remove-PathSafe -TargetPath $_.FullName }
}

# 4) Measured outputs (CSV/HTML, etc.)
if (Test-Path -LiteralPath "measured") {
    Get-ChildItem -Path "measured" -Force -ErrorAction SilentlyContinue |
        ForEach-Object { Remove-PathSafe -TargetPath $_.FullName }
}

Write-Host "clean-runtime-artifacts complete"
